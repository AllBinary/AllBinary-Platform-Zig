// Builds the generated Zig sources.
// The generated code imports files with paths from the source root such as @import("org/allbinary/string/CommonSeps.zig").
// Zig resolves .zig file imports relative to the importing file but checks named imports first,
// so each source file is a module named with its path from the source root.
// Each module only gets the modules its file imports. Giving every module every other module grows with the square of the file count
// and large dependency closures overflowed the zig command line response file.
// Zig only compiles what is referenced so zig build check compiles a test root that references every declaration of the library sources.
// The dependency source directories are nearest first and the first file with a name wins, so a platform variant of a class in a nearer project is used.
// Uses the std.Build API of Zig 0.17 and later.

const std = @import("std");

const SourceFile = struct {
    name: []const u8,
    path: []const u8,
    library: bool,
};

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const dependency_source_paths = b.option([]const u8, "dependency-source-paths", "Dependency source directories separated with ;") orelse "";

    // The source directories are walked when configuring so files added or removed later must configure again
    b.graph.poisonCache();

    var sources: std.ArrayList(SourceFile) = .empty;
    // Module name to its index in sources
    var names: std.StringHashMapUnmanaged(usize) = .empty;
    const source_path = b.root.joinString(b.allocator, "src/main/java") catch @panic("OOM");
    addSources(b, &sources, &names, source_path, true);
    var dependency_iterator = std.mem.tokenizeScalar(u8, dependency_source_paths, ';');
    while (dependency_iterator.next()) |dependency_source_path| {
        addSources(b, &sources, &names, dependency_source_path, false);
    }

    const modules = b.allocator.alloc(*std.Build.Module, sources.items.len) catch @panic("OOM");
    for (sources.items, modules) |source, *module| {
        module.* = b.createModule(.{
            .root_source_file = .{ .cwd_relative = source.path },
            .target = target,
            .optimize = optimize,
        });
    }
    for (sources.items, modules) |source, module| {
        addFileImports(b, source, module, &names, modules);
    }

    // std.testing.refAllDeclsRecursive was removed so the root has its own
    var root_source: std.ArrayList(u8) = .empty;
    root_source.appendSlice(b.allocator,
        \\// Generated by build.zig
        \\const std = @import("std");
        \\
        \\test {
        \\    refAllDeclsRecursive(@This());
        \\}
        \\
        \\fn refAllDeclsRecursive(comptime T: type) void {
        \\    inline for (comptime std.meta.declarations(T)) |decl_name| {
        \\        if (@TypeOf(@field(T, decl_name)) == type) {
        \\            switch (@typeInfo(@field(T, decl_name))) {
        \\                .@"struct", .@"enum", .@"union", .@"opaque" => refAllDeclsRecursive(@field(T, decl_name)),
        \\                else => {},
        \\            }
        \\        }
        \\        _ = &@field(T, decl_name);
        \\    }
        \\}
        \\
        \\
    ) catch @panic("OOM");
    for (sources.items, 0..) |source, index| {
        if (!source.library) continue;
        root_source.appendSlice(b.allocator, b.fmt("pub const source_{d} = @import(\"{s}\");\n", .{ index, source.name })) catch @panic("OOM");
    }

    const files = b.addWriteFiles();
    const root_module = b.createModule(.{
        .root_source_file = files.add("allbinary_root.zig", root_source.items),
        .target = target,
        .optimize = optimize,
    });
    // The root only imports the library sources
    for (sources.items, modules) |source, module| {
        if (source.library) root_module.addImport(source.name, module);
    }

    const tests = b.addTest(.{ .root_module = root_module });
    const check = b.step("check", "Compile every declaration of the generated Zig sources");
    check.dependOn(&tests.step);

    // zig build test runs the tests in each library source, such as the hand written runtime's
    const test_step = b.step("test", "Run the tests of the library sources");
    for (sources.items, modules) |source, module| {
        if (!source.library) continue;
        const module_tests = b.addTest(.{ .root_module = module, .name = std.fs.path.stem(source.name) });
        test_step.dependOn(&b.addRunArtifact(module_tests).step);
    }
}

// Adds the module of each @import("name") in the file that is one of the sources
fn addFileImports(b: *std.Build, source: SourceFile, module: *std.Build.Module, names: *std.StringHashMapUnmanaged(usize), modules: []*std.Build.Module) void {
    const io = b.graph.io;
    const text = std.Io.Dir.cwd().readFileAlloc(io, source.path, b.allocator, .unlimited) catch |err| {
        std.log.warn("Could not read {s}: {s}", .{ source.path, @errorName(err) });
        return;
    };
    const start_text = "@import(\"";
    var position: usize = 0;
    while (std.mem.indexOfPos(u8, text, position, start_text)) |start| {
        const name_start = start + start_text.len;
        const name_end = std.mem.indexOfScalarPos(u8, text, name_start, '"') orelse break;
        position = name_end;
        const name = text[name_start..name_end];
        if (std.mem.eql(u8, name, source.name)) continue;
        if (names.get(name)) |index| module.addImport(name, modules[index]);
    }
}

fn addSources(b: *std.Build, sources: *std.ArrayList(SourceFile), names: *std.StringHashMapUnmanaged(usize), dir_path: []const u8, library: bool) void {
    const io = b.graph.io;
    var dir = std.Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true }) catch {
        std.log.warn("Zig source directory does not exist: {s}", .{dir_path});
        return;
    };
    defer dir.close(io);

    var walker = dir.walk(b.allocator) catch @panic("OOM");
    defer walker.deinit();
    while (walker.next(io) catch |err| @panic(@errorName(err))) |entry| {
        if (entry.kind != .file or !std.mem.endsWith(u8, entry.path, ".zig")) continue;
        const name = b.allocator.dupe(u8, entry.path) catch @panic("OOM");
        std.mem.replaceScalar(u8, name, '\\', '/');
        // A file already added from the project or a nearer dependency, or the project sources listed again as a dependency
        const name_entry = names.getOrPut(b.allocator, name) catch @panic("OOM");
        if (name_entry.found_existing) continue;
        name_entry.value_ptr.* = sources.items.len;
        sources.append(b.allocator, .{
            .name = name,
            .path = b.pathJoin(&.{ dir_path, entry.path }),
            .library = library,
        }) catch @panic("OOM");
    }
}
